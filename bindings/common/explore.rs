/// Owned read-only closed profile handle.
#[derive(Clone)]
pub(crate) struct SharedLoop<P: Payload = StandardPayload> {
    model: SharedModel<P>,
    key: ProfileKey,
    dart: Dart,
}

shared_identity!(SharedLoop, ProfileKey);

impl<P: Payload> SharedLoop<P> {
    fn contextual_dart_id(&self) -> Option<usize> {
        Some(self.dart.id())
    }

    fn from_view(model: SharedModel<P>, view: Loop<'_, P>) -> Self {
        Self {
            model,
            key: view.profile_key().unwrap_or_default(),
            dart: view.dart(),
        }
    }

    fn view(&self) -> Result<Loop<'_, P>, ExploreError> {
        let face = Face::from_dart(self.model.model(), self.dart)
            .ok_or_else(|| missing("loop face", self.dart.id()))?;
        face.loops()
            .into_iter()
            .find(|loop_| loop_.dart() == self.dart)
            .ok_or_else(|| missing("loop", self.dart.id()))
    }

    /// Returns traversal-order dart ids.
    pub(crate) fn darts(&self) -> Result<Vec<usize>, ExploreError> {
        Ok(self.view()?.darts().map(|dart| dart.id()).collect())
    }

    /// Returns traversal-order edges.
    pub(crate) fn edges(&self) -> Result<Vec<SharedEdge<P>>, ExploreError> {
        Ok(self
            .view()?
            .edges()
            .into_iter()
            .map(|view| SharedEdge::from_view(self.model.clone(), view))
            .collect())
    }

    /// Returns traversal-order vertices.
    pub(crate) fn vertices(&self) -> Result<Vec<SharedVertex<P>>, ExploreError> {
        Ok(self
            .view()?
            .vertices()
            .into_iter()
            .map(|view| SharedVertex::from_view(self.model.clone(), view))
            .collect())
    }

    /// Returns the same loop in the opposite traversal orientation.
    pub(crate) fn reversed(&self) -> Result<Self, ExploreError> {
        Ok(Self::from_view(self.model.clone(), self.view()?.reversed()))
    }
}

