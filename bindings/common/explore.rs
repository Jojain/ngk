shared_identity!(SharedFace, FaceKey);

impl<P: Payload> SharedFace<P> {
    fn contextual_dart_id(&self) -> Option<usize> {
        Some(self.dart.id())
    }

    fn from_view(model: SharedModel<P>, view: Face<'_, P>) -> Self {
        Self {
            model,
            key: view.key(),
            dart: view.dart(),
        }
    }

    fn view(&self) -> Result<Face<'_, P>, ExploreError> {
        Face::from_dart(self.model.model(), self.dart)
            .filter(|view| view.key() == self.key)
            .ok_or_else(|| missing("face", format!("{:?}", self.key)))
    }

    /// Returns the outer boundary loop.
    ///
    /// A ring face â€” a cylinder wall â€” is bounded by wrapping loops and has
    /// none; read its whole boundary with [`Self::loops`] instead.
    pub(crate) fn outer_loop(&self) -> Result<SharedLoop<P>, ExploreError> {
        let outer = self
            .view()?
            .outer_loop()
            .ok_or_else(|| missing("outer loop", format!("{:?}", self.key)))?;
        Ok(SharedLoop::from_view(self.model.clone(), outer))
    }

    /// Returns inner boundary loops.
    pub(crate) fn inner_loops(&self) -> Result<Vec<SharedLoop<P>>, ExploreError> {
        Ok(self
            .view()?
            .inner_loops()
            .into_iter()
            .map(|view| SharedLoop::from_view(self.model.clone(), view))
            .collect())
    }

    /// Returns all boundary loops, outer first.
    pub(crate) fn loops(&self) -> Result<Vec<SharedLoop<P>>, ExploreError> {
        Ok(self
            .view()?
            .loops()
            .into_iter()
            .map(|view| SharedLoop::from_view(self.model.clone(), view))
            .collect())
    }

    /// Returns boundary edges in loop order.
    pub(crate) fn edges(&self) -> Result<Vec<SharedEdge<P>>, ExploreError> {
        Ok(self
            .view()?
            .edges()
            .into_iter()
            .map(|view| SharedEdge::from_view(self.model.clone(), view))
            .collect())
    }

    /// Returns boundary vertices in loop order.
    pub(crate) fn vertices(&self) -> Result<Vec<SharedVertex<P>>, ExploreError> {
        Ok(self
            .view()?
            .vertices()
            .into_iter()
            .map(|view| SharedVertex::from_view(self.model.clone(), view))
            .collect())
    }

    /// Returns a clone of the support surface.
    pub(crate) fn surface(&self) -> Result<Surface, ExploreError> {
        Ok(self.view()?.surface().clone())
    }

    /// Returns the pcurve assigned to a boundary dart, if present.
    pub(crate) fn pcurve(&self, dart: usize) -> Result<Option<TrimmedCurve2>, ExploreError> {
        let dart = self.model.checked_dart(dart)?;
        Ok(self.view()?.pcurve(dart))
    }

    /// Returns the same face in the opposite orientation.
    pub(crate) fn reversed(&self) -> Result<Self, ExploreError> {
        Ok(Self::from_view(self.model.clone(), self.view()?.reversed()))
    }

    /// Copies this face into an owned shape for a modeling constructor.
    #[cfg(feature = "python")]
    pub(crate) fn isolated_shape(&self) -> Result<Shape<FaceTag, P>, ExploreError> {
        let (model, dart) = self.view()?.isolate();
        let key = model.cell_key_unchecked::<Cell2>(dart);
        Ok(Shape::new(model, key))
    }
}

